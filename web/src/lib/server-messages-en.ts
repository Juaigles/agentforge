/** Traducción de un mensaje con código; `undefined` si el código no se conoce (p. ej. de un servidor más reciente). */
function translate(message: ServerMessage): string | undefined {
  // La causa de un fallo puede ser un problema de validación de un workflow, que tiene su propia tabla.
  const render = SERVER_EN[message.code as ServerCode] ?? VALIDATION_EN[message.code as ValidationCode];
  if (!render) return undefined;
  return render(flattenParams(message.params, (nested) => translate(nested) ?? nested.message ?? ''));
}

/**
 * Texto del servidor en el idioma de la interfaz (reactivo): en español, el que envía o guarda el servidor; en
 * inglés, el traducido a partir de su código y sus parámetros. Sin código (lo anterior a la 1.0, lo que viene de
 * fuera) o con uno desconocido se muestra el texto tal cual.
 */
export function serverText(text: string | null | undefined, i18n?: ServerMessage | null): string {
  if (locale.value !== 'en' || !i18n || typeof i18n.code !== 'string') return text ?? '';
  return translate(i18n) ?? text ?? '';
}
